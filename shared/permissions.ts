export type CanonicalRole = 'ADMIN' | 'REGIONAL_MANAGER' | 'MANAGER' | 'STORE_MANAGER' | 'SALES' | 'SALE_ONLINE' | 'CUSTOMER_CARE' | 'TECHNICIAN' | 'TECH_LEAD' | 'CASHIER' | 'WAREHOUSE' | 'INVENTORY_MANAGER' | 'ACCOUNTANT';
export type Permission =
  | 'POS_CHECKOUT'
  | 'INVOICE_READ'
  | 'INVOICE_REFUND'
  | 'TRADE_IN_READ'
  | 'CRM_READ'
  | 'CRM_ASSIGN'
  | 'PARTNER_DIRECTORY_READ'
  | 'INVENTORY_TRANSFER_CREATE'
  | 'FINANCE_VIEW'
  | 'FINANCE_POST'
  | 'ATTENDANCE_REVIEW'
  | 'CHANNEL_MANAGE';

const aliases: Record<string, CanonicalRole> = {
  SALE: 'SALES', SALES: 'SALES',
  TECH: 'TECHNICIAN', TECHNICIAN: 'TECHNICIAN',
  CSKH: 'CUSTOMER_CARE', CUSTOMER_CARE: 'CUSTOMER_CARE'
};

export function normalizeRole(value: unknown): string {
  const role = String(value || '').trim().toUpperCase();
  return aliases[role] || role;
}

