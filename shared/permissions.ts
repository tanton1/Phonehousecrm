  REGIONAL_MANAGER: ['POS_CHECKOUT', 'INVOICE_READ', 'INVOICE_REFUND', 'TRADE_IN_READ', 'CRM_READ', 'CRM_ASSIGN', 'PARTNER_DIRECTORY_READ', 'INVENTORY_TRANSFER_CREATE', 'FINANCE_VIEW', 'FINANCE_POST', 'ATTENDANCE_REVIEW', 'CHANNEL_MANAGE'],
  MANAGER: ['POS_CHECKOUT', 'INVOICE_READ', 'INVOICE_REFUND', 'TRADE_IN_READ', 'CRM_READ', 'CRM_ASSIGN', 'PARTNER_DIRECTORY_READ', 'INVENTORY_TRANSFER_CREATE', 'FINANCE_VIEW', 'FINANCE_POST', 'ATTENDANCE_REVIEW', 'CHANNEL_MANAGE'],
  STORE_MANAGER: ['POS_CHECKOUT', 'INVOICE_READ', 'INVOICE_REFUND', 'TRADE_IN_READ', 'CRM_READ', 'CRM_ASSIGN', 'PARTNER_DIRECTORY_READ', 'INVENTORY_TRANSFER_CREATE', 'FINANCE_VIEW', 'ATTENDANCE_REVIEW'],
